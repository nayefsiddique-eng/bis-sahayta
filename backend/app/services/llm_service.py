class GeminiProvider(LLMProvider):
    """Google Gemini via the google-generativeai SDK."""

    name = "gemini"

    def __init__(self) -> None:
        if not settings.GEMINI_API_KEY:
            raise HTTPException(
                status_code=502,
                detail={"error_code": "LLM_CONFIG_ERROR", "message": "GEMINI_API_KEY is not set in environment or backend/.env file."}
            )
        try:
            import google.generativeai as genai  # type: ignore
            genai.configure(api_key=settings.GEMINI_API_KEY)
            self._model = genai.GenerativeModel(settings.GEMINI_MODEL)
        except ImportError as exc:
            logger.error(f"google-generativeai package missing: {exc}")
            raise HTTPException(
                status_code=502,
                detail={"error_code": "LLM_DEPENDENCY_ERROR", "message": "google-generativeai package is not installed."}
            ) from exc

    async def complete(self, prompt: str, *, system: str = "", max_tokens: int = 1024) -> str:
        import asyncio
        import re
        import google.generativeai as genai  # type: ignore

        full_prompt = f"{system}\n\n{prompt}" if system else prompt
        loop = asyncio.get_running_loop()
        attempts = 3
        max_wait = 25

        for attempt in range(attempts):
            try:
                response = await loop.run_in_executor(
                    None,
                    lambda: self._model.generate_content(
                        full_prompt,
                        generation_config=genai.types.GenerationConfig(max_output_tokens=max_tokens),
                    ),
                )
                return response.text
            except Exception as exc:
                msg = str(exc)
                is_429 = (
                    "429" in msg
                    or "RESOURCE_EXHAUSTED" in msg
                    or "ResourceExhausted" in type(exc).__name__
                    or "quota" in msg.lower()
                )
                if is_429:
                    m = re.search(r"retry[^0-9]{0,30}(\d+)", msg, re.I)
                    wait = int(m.group(1)) + 1 if m else 2 ** (attempt + 1)
                    if attempt < attempts - 1 and wait <= max_wait and "PerDay" not in msg:
                        logger.warning(f"Gemini 429, retrying in {wait}s (attempt {attempt + 1}/{attempts})")
                        await asyncio.sleep(wait)
                        continue
                    logger.error(f"Gemini rate limit exhausted: {exc}")
                    _q = re.search(r'quota_id: "([^"]+)"', msg)
                    _qid = _q.group(1) if _q else None
                    raise HTTPException(
                        status_code=429,
                        detail={"error_code": "LLM_RATE_LIMITED", "message": "Gemini rate limit reached. Please retry shortly.", "retry_after": wait, "retry_after_seconds": wait, "quota_id": _qid},
                        headers={"Retry-After": str(wait)},
                    ) from exc
                logger.error(f"GeminiProvider API execution error: {exc}")
                raise HTTPException(
                    status_code=502,
                    detail={"error_code": "LLM_PROVIDER_ERROR", "message": f"Gemini API failure: {str(exc)}"},
                ) from exc


